test('the engine is unpacked once per shipped build, from the installer or from npm', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'mx-rig-engine-'))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const shipped = join(dir, 'mihomo.gz')
  await writeFile(shipped, gzipSync(Buffer.from('#!/bin/sh\necho mihomo\n')))
  const cacheDir = join(dir, 'cache')
  await mkdir(join(cacheDir, 'old-digest'), { recursive: true })
  const first = await prepareEngine({ shipped, cacheDir, platform: 'darwin' })
  assert.equal(readFileSync(first, 'utf8'), '#!/bin/sh\necho mihomo\n')
  if (process.platform !== 'win32') assert.equal((await stat(first)).mode & 0o111, 0o111, 'executable')
  assert.equal(await prepareEngine({ shipped, cacheDir, platform: 'darwin' }), first)
  assert.equal(existsSync(join(cacheDir, 'old-digest')), false, 'an earlier engine is not kept around')
  assert.equal(shippedEngine({ packaged: true, resourcesPath: '/App/Resources', platform: 'win32', arch: 'x64' }), join('/App/Resources', 'mihomo', 'win32-x64', 'mihomo.exe.gz'))
  assert.throws(() => shippedEngine({ packaged: false, platform: 'plan9', arch: 'mips', resolve: () => { throw new Error('missing') } }), /npm install/)
  await assert.rejects(prepareEngine({ shipped: join(dir, 'none.gz'), cacheDir }), /没有海外通道引擎/)
})

test('with the real Mihomo: the compiled config starts, proxies on loopback only, and stops', async (t) => {
  let shipped
  try {
    shipped = shippedEngine({ packaged: false })
  } catch {
    return t.skip('no Mihomo engine package for this platform')
  }
  const dir = await mkdtemp(join(tmpdir(), 'mx-rig-oversea-real-'))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const site = createHttpServer((req, res) => res.end('local page')).listen(0, '127.0.0.1')
  t.after(() => site.close())
  await new Promise((resolve) => site.once('listening', resolve))
  // The fake hysteria2 node never answers; a loopback page is direct by rule.
  const viaProxy = ({ port }) =>
    new Promise((resolve) => {
      const started = Date.now()
      const req = httpRequest({ host: '127.0.0.1', port, path: `http://127.0.0.1:${site.address().port}/`, headers: { host: `127.0.0.1:${site.address().port}` } }, (res) => {
        let body = ''
        res.on('data', (chunk) => (body += chunk))
        res.on('end', () => resolve({ ok: body === 'local page', latencyMs: Date.now() - started, reason: body }))
      })
      req.once('error', (error) => resolve({ ok: false, latencyMs: 0, reason: error.message }))
      req.end()
    })
  const oversea = await LauncherOversea.open({
    dir,
    network: fakeNetwork(),
    sdk: { ensureElectronLauncherUserOverseaSubscription: async () => ({ ready: true, status: 'ready', siteIds: ['oversea-main'], subscription: { yaml: SUBSCRIPTION } }) },
    compiler,
    engine: () => prepareEngine({ shipped, cacheDir: join(dir, 'engine') }),
    probe: viaProxy
  })
  const ready = await oversea.start()
  assert.deepEqual([ready.state, ready.verified], ['ready', true], ready.text)
  await oversea.setBrowser(true)
  const port = Number(new URL(oversea.browserProxy().server).port)
  // Nothing listens anywhere but 127.0.0.1 on that one port.
  if (process.platform !== 'win32' && spawnSync('lsof', ['-v'], { stdio: 'ignore' }).status === 0) {
    const pid = readFileSync(join(dir, 'mx-rig-oversea', 'mihomo.pid'), 'utf8').trim()
    const listening = spawnSync('lsof', ['-nP', '-a', '-p', pid, '-iTCP', '-sTCP:LISTEN', '-Fn'], { encoding: 'utf8' }).stdout
    assert.deepEqual(listening.split('\n').filter((line) => line.startsWith('n')), [`n127.0.0.1:${port}`])
  }
  await oversea.stop()
  assert.equal(await new Promise((resolve) => netConnect(port, '127.0.0.1').once('connect', function () { this.destroy(); resolve(true) }).once('error', () => resolve(false))), false, 'stopped means stopped')
})
