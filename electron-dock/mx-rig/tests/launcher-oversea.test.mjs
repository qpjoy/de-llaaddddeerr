test("the platform's compiler, then only Rig's loopback port is left listening", () => {
  const { yaml, policy } = compileConfig(SUBSCRIPTION, { compiler, port: 47123 })
  const config = parse(yaml)
  assert.equal(policy, 'Oversea')
  assert.deepEqual([config['mixed-port'], config['allow-lan'], config['bind-address'], config.ipv6, config.tun.enable], [47123, false, '127.0.0.1', false, false])
  for (const key of ['external-controller', 'secret', 'port', 'socks-port', 'geodata-mode', 'geo-auto-update', 'geox-url']) assert.ok(!(key in config), `no ${key}`)
  assert.ok(!('listen' in config.dns), 'no DNS listener')
  assert.ok(!config.rules.some((rule) => /^GEO(SITE|IP),/.test(rule)), 'nothing to download from GitHub before starting')
  assert.ok(config.rules.includes('IP-CIDR,100.99.0.0/16,DIRECT,no-resolve'), "Internal's reserved ranges stay direct")
  assert.ok(config.rules.includes('DOMAIN-SUFFIX,cn,DIRECT'), 'common Chinese sites stay direct without geodata')
  assert.equal(config.rules.at(-1), 'MATCH,Oversea')
  assert.equal(config.proxies[0].password, 'per-user-secret-token', 'the proxy still needs its credential')
  assert.doesNotMatch(yaml, /tester@example\.com/, 'the comments naming the account are not kept')
  // A compiler that turned on a virtual adapter or the LAN is refused.
  const unsafe = { ...compiler, renderRuntimeConfig: (input) => ({ ...compiler.renderRuntimeConfig(input), yaml: compiler.renderRuntimeConfig(input).yaml.replace('enable: false', 'enable: true') }) }
  assert.throws(() => compileConfig(SUBSCRIPTION, { compiler: unsafe, port: 47123 }), /不安全/)
})

// A Mihomo stand-in: listens on the port its config names, until killed.
function fakeMihomo({ crashAfterMs = null } = {}) {
  const runs = []
  const spawnImpl = (binary, args) => {
    const child = new EventEmitter()
    child.stdout = new PassThrough()
    child.stderr = new PassThrough()
    child.pid = 900000 + runs.length
    child.exitCode = null
    child.signalCode = null
    const config = readFileSync(args[args.indexOf('-f') + 1], 'utf8')
    const server = createNetServer((socket) => socket.end()).listen(parse(config)['mixed-port'], '127.0.0.1')
    const exit = (code) => {
      if (child.exitCode !== null) return
      child.exitCode = code
      server.close()
      child.emit('exit', code)
    }
    child.kill = () => exit(0)
    if (crashAfterMs) setTimeout(() => (child.stderr.write('time="x" level=error msg="hysteria2 handshake failed"\n'), exit(1)), crashAfterMs)
    runs.push({ binary, args, config, mode: null })
    return child
  }
  return { runs, spawnImpl }
}

const fakeNetwork = () => ({
  session: { baseUrl: 'http://10.88.100.5:18090', userId: 'u-42', accessToken: 'mx-v1-user-token' },
  overseaSession() {
    return this.session
  }
})

async function setup(t, { answers, crashAfterMs, probe } = {}) {
  const dir = await mkdtemp(join(tmpdir(), 'mx-rig-oversea-'))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const ensured = []
  const queue = [...(answers ?? [{ ready: true, status: 'ready', siteIds: ['oversea-main'], subscription: { yaml: SUBSCRIPTION } }])]
  const sdk = {
    ensureElectronLauncherUserOverseaSubscription: async (input) => {
      ensured.push(input)
      const next = queue.length > 1 ? queue.shift() : queue[0]
      if (next instanceof Error) throw next
      return next
    }
  }
  const mihomo = fakeMihomo({ crashAfterMs })
  const seen = []
  const network = fakeNetwork()
  const oversea = await LauncherOversea.open({
    dir,
    network,
    sdk,
    compiler,
    engine: async () => '/opt/mihomo',
    spawnImpl: mihomo.spawnImpl,
    probe: probe ?? (async () => ({ ok: true, latencyMs: 321 })),
    retryDelayMs: 5,
    onChange: (snap) => seen.push(snap)
  })
  t.after(() => oversea.shutdown())
  return { dir, ensured, mihomo, seen, network, oversea }
}

test('turned on: subscription through the VIP, a 0600 config, a loopback proxy, a verified line', async (t) => {
  const { dir, ensured, mihomo, seen, oversea } = await setup(t, {
    answers: [
      { ready: false, status: 'pending-runtime-sync', siteIds: ['oversea-main'], subscription: null },
      { ready: true, status: 'ready', siteIds: ['oversea-main'], subscription: { yaml: SUBSCRIPTION } }
    ]
  })
  const ready = await oversea.start()
  assert.deepEqual([ready.state, ready.verified, ready.latencyMs, ready.sites], ['ready', true, 321, ['oversea-main']])
  assert.match(ready.text, /已就绪（试访问 321 ms）/)
  assert.ok(seen.some((snap) => snap.state === 'syncing'), 'a line still being opened is waited for, not reported as ready')
  assert.deepEqual([ensured[0].baseUrl, ensured[0].userId, ensured[0].accessToken, ensured[0].requestedBy], ['http://10.88.100.5:18090', 'u-42', 'mx-v1-user-token', 'mx-rig-desktop'])
  const [run] = mihomo.runs
  assert.deepEqual(run.args.slice(0, 2), ['-d', join(dir, 'mx-rig-oversea')])
  const config = join(dir, 'mx-rig-oversea', 'config.yaml')
  if (process.platform !== 'win32') assert.equal((await stat(config)).mode & 0o777, 0o600)
  // The test browser uses it only when chosen.
  assert.equal(oversea.browserProxy(), null)
  await oversea.setBrowser(true)
  const proxy = oversea.browserProxy()
  assert.deepEqual(proxy, { id: CHANNEL_ID, server: `http://127.0.0.1:${parse(run.config)['mixed-port']}`, bypass: BROWSER_BYPASS })
  assert.equal(oversea.snapshot().usingBrowser, true)
  // Nothing the page receives names the credential, the token, the port or the YAML.
  const shown = JSON.stringify([...seen, oversea.snapshot()])
  for (const secret of ['per-user-secret-token', 'mx-v1-user-token', String(parse(run.config)['mixed-port']), 'hysteria2', 'mixed-port'])
    assert.ok(!shown.includes(secret), `the page never sees ${secret}`)
  // Turned off: the process ends, the config with the credential is gone, and that is remembered.
  const off = await oversea.stop()
  assert.equal(off.state, 'off')
  assert.equal(oversea.browserProxy(), null)
  assert.equal(existsSync(config), false)
  assert.deepEqual(JSON.parse(await readFile(join(dir, 'mx-rig-oversea.json'), 'utf8')), { enabled: false, browser: true })
})

test('the account comes and goes with the network: signed out it stops, signed in again it starts again', async (t) => {
  const { mihomo, oversea, network } = await setup(t)
  await oversea.start()
  await oversea.setBrowser(true)
  oversea.networkChanged({ status: 'ready', identity: { kind: 'anonymous' } })
  await oversea.shutdown()
  assert.equal(oversea.snapshot().state, 'unavailable')
  assert.equal(oversea.browserProxy(), null)
  assert.equal(mihomo.runs.length, 1)
  network.session = { baseUrl: 'http://10.88.100.5:18090', userId: 'u-42', accessToken: 'mx-v1-next' }
  oversea.networkChanged({ status: 'applying', identity: { kind: 'user' } })
  oversea.networkChanged({ status: 'ready', identity: { kind: 'user' } })
  await oversea.shutdown().then(() => null)
  // shutdown() halted it again; what matters is that the ready transition started a second run.
  assert.equal(mihomo.runs.length, 2, 'a channel left on starts again with the account')
  // Never turned on: nothing starts.
  const fresh = await setup(t)
  fresh.oversea.networkChanged({ status: 'ready', identity: { kind: 'user' } })
  await new Promise((resolve) => setTimeout(resolve, 30))
  assert.equal(fresh.mihomo.runs.length, 0)
  // Without the account's session it waits instead of asking.
  fresh.network.session = null
  assert.equal((await fresh.oversea.start()).state, 'unavailable')
  assert.equal(fresh.ensured.length, 0)
})

test('what goes wrong is said in words; a proxy that dies takes the browser off it', async (t) => {
  const denied = await setup(t, { answers: [new Error('Oversea ensure failed: HTTP 403 missing scope: oversea.subscription.ensure')] })
  assert.match((await denied.oversea.start()).text, /没有海外权限/)
  assert.equal(denied.mihomo.runs.length, 0)
  const blocked = await setup(t, { answers: [{ ready: false, status: 'blocked', siteIds: [], subscription: null }] })
  assert.match((await blocked.oversea.start()).text, /还没有可用的海外线路/)
  const pending = await setup(t, { answers: [{ ready: false, status: 'pending-runtime-sync', siteIds: [], subscription: null }] })
  assert.match((await pending.oversea.start()).text, /还在开通/)
  assert.equal(pending.ensured.length, 4, 'a few tries, then it says so')
  const unverified = await setup(t, { probe: async () => ({ ok: false, latencyMs: 10000, reason: '超时' }) })
  const half = await unverified.oversea.start()
  assert.deepEqual([half.state, half.verified], ['ready', false])
  assert.match(half.text, /试访问没有成功（超时）/)
  const crash = await setup(t, { crashAfterMs: 80 })
  await crash.oversea.start()
  await crash.oversea.setBrowser(true)
  await new Promise((resolve) => setTimeout(resolve, 150))
  const died = crash.oversea.snapshot()
  assert.equal(died.state, 'error')
  assert.match(died.text, /意外退出：level=error msg="hysteria2 handshake failed"/)
  assert.equal(crash.oversea.browserProxy(), null)
})

test('a proxy left behind by a crash is stopped only if it really is Mihomo', async (t) => {
  const dir = await mkdtemp(join(tmpdir(), 'mx-rig-oversea-orphan-'))
  t.after(() => rm(dir, { recursive: true, force: true }))
  await mkdir(join(dir, 'mx-rig-oversea'), { recursive: true })
  const reap = async (name) => {
    const child = spawn(process.execPath, ['-e', 'setInterval(() => {}, 1000)'])
    await writeFile(join(dir, 'mx-rig-oversea', 'mihomo.pid'), String(child.pid))
    await writeFile(join(dir, 'mx-rig-oversea', 'config.yaml'), 'password: x')
    const exited = new Promise((resolve) => child.once('exit', () => resolve(true)))
    await LauncherOversea.open({ dir, network: fakeNetwork(), sdk: {}, compiler, engine: async () => '', processName: async () => name })
    const gone = await Promise.race([exited, new Promise((resolve) => setTimeout(() => resolve(false), 1000))])
    child.kill()
    return gone
  }
  assert.equal(await reap('/Applications/MX Rig.app/.../mihomo'), true)
  assert.equal(await reap('node'), false, 'a reused process ID is left alone')
  assert.equal(existsSync(join(dir, 'mx-rig-oversea', 'config.yaml')), false, 'the stale credential is removed')
})

test('the probe answers through a CONNECT proxy, and says why when it cannot', async (t) => {
  // Refused outright, and refused by the proxy.
  assert.equal((await probeThroughProxy({ port: 1, timeoutMs: 2000 })).ok, false)
  const refusing = createNetServer((socket) => socket.once('data', () => socket.end('HTTP/1.1 502 Bad Gateway\r\n\r\n'))).listen(0, '127.0.0.1')
  t.after(() => refusing.close())
  await new Promise((resolve) => refusing.once('listening', resolve))
  const refused = await probeThroughProxy({ port: refusing.address().port, timeoutMs: 2000 })
  assert.deepEqual([refused.ok, refused.reason], [false, '代理拒绝了连接（502）'])
  // The whole way: CONNECT, TLS, 204 — with a certificate made for this test.
  const dir = await mkdtemp(join(tmpdir(), 'mx-rig-probe-'))
  t.after(() => rm(dir, { recursive: true, force: true }))
  const made = spawnSync('openssl', ['req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-days', '1', '-subj', '/CN=localhost', '-addext', 'subjectAltName=DNS:localhost', '-keyout', join(dir, 'key.pem'), '-out', join(dir, 'cert.pem')], { stdio: 'ignore' })
  if (made.status !== 0) return t.skip('openssl is not available')
  const cert = readFileSync(join(dir, 'cert.pem'))
  const site = createTlsServer({ key: readFileSync(join(dir, 'key.pem')), cert }, (socket) =>
    socket.once('data', () => socket.end('HTTP/1.1 204 No Content\r\nContent-Length: 0\r\nConnection: close\r\n\r\n'))
  ).listen(0, '127.0.0.1')
  t.after(() => site.close())
  await new Promise((resolve) => site.once('listening', resolve))
  const proxy = createNetServer((client) =>
    client.once('data', (head) => {
      const [, , port] = /^CONNECT ([^:]+):(\d+)/.exec(head.toString())
      const upstream = netConnect(Number(port), '127.0.0.1', () => {
        client.write('HTTP/1.1 200 Connection Established\r\n\r\n')
        client.pipe(upstream).pipe(client)
      })
    })
  ).listen(0, '127.0.0.1')
  t.after(() => proxy.close())
  await new Promise((resolve) => proxy.once('listening', resolve))
  const through = await probeThroughProxy({ port: proxy.address().port, url: `https://localhost:${site.address().port}/generate_204`, tlsOptions: { ca: cert } })
  assert.deepEqual([through.ok, through.status], [true, 204])
})

test('the Runtime takes a local channel the way it takes the service one, and only a loopback one', () => {
  const policy = { revision: 'rev-1', allowedTools: [], egress: { activeId: null, browser: null } }
  const local = localChannel({ id: CHANNEL_ID, server: 'http://127.0.0.1:47123', bypass: BROWSER_BYPASS })
  const decorated = withLocalEgress(policy, local)
  assert.equal(decorated.revision, 'rev-1+launcher-oversea', 'a confirmation given on one path is not spent on another')
  assert.deepEqual(decorated.egress.browserProxy, { id: CHANNEL_ID, server: 'http://127.0.0.1:47123', bypass: BROWSER_BYPASS })
  assert.equal(withLocalEgress(policy, null), policy, 'without one, the service policy passes untouched')
  assert.notEqual(BrowserTools.channelOf(decorated).key, BrowserTools.channelOf(policy).key, 'the browser reopens on it')
  for (const bad of ['http://10.0.0.5:7890', 'https://127.0.0.1:7890', 'http://user:pw@127.0.0.1:7890', 'socks5://127.0.0.1:7890', 'http://127.0.0.1'])
    assert.throws(() => localChannel({ id: CHANNEL_ID, server: bad }), /loopback/, bad)
  assert.equal(localChannel(null), null)
})

