export function mapExternalEnvironment(source = process.env, target = process.env) {
  for (const [externalName, kernelName] of Object.entries(ENVIRONMENT_MAP)) {
    if (Object.prototype.hasOwnProperty.call(source, externalName)) {
      target[kernelName] = String(source[externalName] ?? '')
    } else {
      // A shell that previously ran the legacy service may still contain MXT_*
      // values. They are not public configuration for this service and must
      // not silently point a runner back at the legacy namespace or database.
      delete target[kernelName]
    }
  }
  for (const [kernelName, value] of Object.entries(DEFAULTS)) {
    if (!target[kernelName]?.trim()) target[kernelName] = value
  }
  // MX Rig is exposed directly over plain HTTP by its local server and the
  // bundled NodePort. When no advertised URL was supplied, the legacy kernel
  // cannot infer that scheme and would otherwise emit a Secure session cookie
  // that browsers silently drop. An explicit cookie setting or public URL
  // continues to win.
  if (!target.MXT_INSECURE_COOKIES?.trim() && !target.MXT_PUBLIC_URL?.trim()) {
    target.MXT_INSECURE_COOKIES = 'true'
  }
  return target
}
