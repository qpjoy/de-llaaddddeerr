"""Read-only persistent mount checks; no systemd or Linux mounts required."""
from pathlib import Path
import tempfile
import unittest
from unittest import mock

from test_move import move


class MountConfigTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix='mx-etcd-mount-config-')
        self.addCleanup(temporary.cleanup)
        root = Path(temporary.name)
        self.fstab = root / 'fstab'
        self.fragment = root / 'generator/var-lib-etcd.mount'
        self.fragment.parent.mkdir()
        self.source = '/data/mx-runtime/etcd'
        self.fstab.write_text(self.source + ' /var/lib/etcd none bind 0 0\n')
        # Real production example: show's What/Options describe the active
        # block device. Only the generated fragment describes the boot source.
        self.properties = {
            'LoadState': 'loaded', 'FragmentPath': str(self.fragment),
            'SourcePath': str(self.fstab), 'DropInPaths': '', 'NeedDaemonReload': 'no',
            'What': '/dev/nvme0n1p1', 'Where': '/var/lib/etcd',
            'Options': 'rw,noatime,seclabel,attr2,inode64,logbufs=8,logbsize=32k,noquota'}
        self.fragment.write_text('# Automatically generated by systemd-fstab-generator\n\n'
                                 '[Unit]\nSourcePath=' + str(self.fstab) + '\n'
                                 'Before=local-fs.target\n\n[Mount]\nWhere=/var/lib/etcd\n'
                                 'What=' + self.source + '\nType=none\nOptions=bind\n')
        self.original_fragment = self.fragment.read_text()
        for name, value in [('FSTAB', self.fstab), ('GENERATED_MOUNT', self.fragment)]:
            patcher = mock.patch.object(move, name, value)
            patcher.start()
            self.addCleanup(patcher.stop)
        patcher = mock.patch.object(move, 'safe_path')
        patcher.start()
        self.addCleanup(patcher.stop)

    def check(self, source=None, raw=None):
        if raw is None:
            raw = ''.join(name + '=' + value + '\n' for name, value in self.properties.items()).encode()
        with mock.patch.object(move, 'run', return_value=raw) as execute:
            move.Host().persistent_mount(source or self.source)
        self.assertEqual(len(execute.call_args_list), 1)
        self.assertEqual(execute.call_args[0][0][:2], ['systemctl', 'show'])

    def test_real_fstab_generated_bind_passes_without_writes_or_reloads(self):
        self.check()
        self.assertEqual(self.fragment.read_text(), self.original_fragment)

    def test_rejects_native_unit_dropins_masked_and_missing_units(self):
        for key, value in [('FragmentPath', '/etc/systemd/system/var-lib-etcd.mount'),
                           ('FragmentPath', '/run/systemd/transient/var-lib-etcd.mount'),
                           ('DropInPaths', '/etc/systemd/system/var-lib-etcd.mount.d/override.conf'),
                           ('SourcePath', ''), ('LoadState', 'masked'), ('LoadState', 'not-found')]:
            with self.subTest(key=key, value=value), mock.patch.dict(self.properties, {key: value}):
                with self.assertRaisesRegex(move.Refuse, '必须仅由 /etc/fstab 生成'):
                    self.check()

    def test_rejects_pending_reload_without_running_it(self):
        self.properties['NeedDaemonReload'] = 'yes'
        with self.assertRaisesRegex(move.Refuse, '尚未被 systemd 重新加载'):
            self.check()

    def test_discovery_rejects_mount_override_before_any_runtime_or_api_request(self):
        self.properties['FragmentPath'] = '/etc/systemd/system/var-lib-etcd.mount'
        raw = ''.join(name + '=' + value + '\n' for name, value in self.properties.items()).encode()
        host = move.Host()
        with mock.patch.object(move.sys, 'platform', 'linux'), \
                mock.patch.object(move.os, 'geteuid', return_value=0), \
                mock.patch.object(move.shutil, 'which', return_value='/offline/tool'), \
                mock.patch.object(move, 'run', return_value=raw) as execute, \
                mock.patch.object(host, 'runtime') as runtime, \
                mock.patch.object(host, 'kubectl') as kubectl:
            with self.assertRaisesRegex(move.Refuse, '必须仅由 /etc/fstab 生成'):
                host.discover()
        self.assertEqual(len(execute.call_args_list), 1)
        self.assertEqual(execute.call_args[0][0][:2], ['systemctl', 'show'])
        runtime.assert_not_called()
        kubectl.assert_not_called()

    def test_rejects_missing_duplicate_and_failed_properties(self):
        for raw in [b'', b'LoadState=loaded\nLoadState=loaded\n', b'sensitive-invalid-response']:
            with self.subTest(raw=raw), self.assertRaises(move.Refuse) as error:
                self.check(raw=raw)
            self.assertNotIn('sensitive-', str(error.exception))
        with mock.patch.object(move, 'run', side_effect=move.CommandFailed('systemctl', 1, b'secret')):
            with self.assertRaises(move.Refuse) as error:
                move.Host().persistent_mount(self.source)
        self.assertNotIn('secret', str(error.exception))

    def test_fstab_source_drift_is_rejected_before_systemctl(self):
        with mock.patch.object(move, 'run') as execute:
            with self.assertRaisesRegex(move.Refuse, '源目录与预期不一致'):
                move.Host().persistent_mount('/wrong/etcd')
        execute.assert_not_called()

    def test_checks_fragment_source_even_when_show_reports_expected_live_mount(self):
        self.properties['What'] = self.source
        self.fragment.write_text(self.original_fragment.replace('What=' + self.source, 'What=/stale/etcd'))
        with self.assertRaisesRegex(move.Refuse, '生成挂载配置与 fstab/预期源目录不一致'):
            self.check()

    def test_rejects_missing_duplicate_wrong_section_and_unsafe_generated_fields(self):
        changes = [('What=' + self.source + '\n', ''),
                   ('[Mount]', '[Service]'),
                   ('Where=/var/lib/etcd', 'Where=/other'),
                   ('Options=bind', 'Options=ro,bind'),
                   ('Options=bind', 'Options=defaults'),
                   ('Options=bind', 'Options=bind\nWhat=' + self.source),
                   ('Options=bind', 'Options=bind\\\n,ro')]
        for old, new in changes:
            with self.subTest(new=new):
                self.fragment.write_text(self.original_fragment.replace(old, new))
                with self.assertRaises(move.Refuse):
                    self.check()

    def test_validates_new_generation_after_fstab_update_and_reload(self):
        target = '/var/lib/mx-move/etcd-data/mx-etcd-new'
        self.fstab.write_bytes(move.change_fstab(self.fstab.read_bytes(), target))
        with self.assertRaisesRegex(move.Refuse, '生成挂载配置与 fstab/预期源目录不一致'):
            self.check(target)
        self.fragment.write_text(self.original_fragment.replace(self.source, target))
        self.check(target)


if __name__ == '__main__':
    unittest.main()
