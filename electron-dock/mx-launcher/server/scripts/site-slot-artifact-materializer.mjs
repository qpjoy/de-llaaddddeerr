const scriptDir = dirname(fileURLToPath(import.meta.url));
const mxRoot = resolveMxRoot(scriptDir);
const args = process.argv.slice(2);
const kind = args.find((arg) => !arg.startsWith('--')) || 'all';
const outDirArg = optionValue('--out-dir');
